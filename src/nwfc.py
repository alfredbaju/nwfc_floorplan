"""Nested WFC (N-WFC) — macro/micro split with diagonal exterior generation.

Implements Algorithm 1 and Section III-C of the base paper (Nie, Zheng,
Zhuang & Togelius, 2024), adapted to this project's floor-plan tileset:

  - I-WFC: solves one small, fixed-size C x C subgrid, inheriting a
    pre-collapsed first row and/or first column from already-generated
    neighboring subgrids (its "preconstraints"). Internally, I-WFC is just
    the baseline WFC engine from wfc_core.py with those cells pinned before
    the normal entropy-selection loop runs.

  - Exterior process: splits the full M x N grid into an A x B arrangement
    of subgrids and solves them in *diagonal* order (layer = a + b), so
    every subgrid only ever needs its top neighbor's last row and its left
    neighbor's last column, both already finished by the time it runs.
    Solved subgrids are stitched together by overlapping one shared row and
    one shared column with each neighbor, exactly as described in the base
    paper's Section III-C2.

M and N are *derived* from A, B, C (not chosen independently), following
the base paper's formula: M = A*(C-1) + 1, N = B*(C-1) + 1.
"""

import sys
import os
import random

sys.path.insert(0, os.path.dirname(__file__))

from wfc_core import WFCGrid, Contradiction  # noqa: E402


class NWFCResult:
    """Container for a finished N-WFC run: the stitched global grid, the
    individual subgrids (useful for debugging/visualizing the diagonal
    process), and bookkeeping on how much I-WFC backtracking occurred."""

    def __init__(self, global_grid, subgrids, subgrid_restarts, A, B, C, exterior_backtracks=0):
        self.global_grid = global_grid  # 2-D list of tile ids, size M x N
        self.subgrids = subgrids  # dict (a, b) -> 2-D list of tile ids, size C x C
        self.subgrid_restarts = subgrid_restarts  # dict (a, b) -> int restarts used
        self.A, self.B, self.C = A, B, C
        self.exterior_backtracks = exterior_backtracks  # count of subgrids that had to be redone

    @property
    def total_restarts(self):
        """Total I-WFC-level backtracking across all subgrids. Per the base
        paper's determinacy proof (Section IV-D2), this is the *only*
        place backtracking should ever occur under N-WFC with a
        subcomplete tileset — the exterior process itself should never
        need to redo a subgrid once it's accepted. This metric is the
        direct evidence for that claim (feeds E2 in the experiment plan)."""
        return sum(self.subgrid_restarts.values())

    @property
    def rows(self):
        return len(self.global_grid)

    @property
    def cols(self):
        return len(self.global_grid[0]) if self.global_grid else 0


def _diagonal_order(A, B):
    """Yield (a, b) subgrid indices (0-indexed) in the diagonal, layer-by-
    layer sequence described in Section III-C2 of the base paper: top-left
    to bottom-right, so every subgrid's top and left neighbors are always
    already generated by the time it's this subgrid's turn."""
    for layer in range(A + B - 1):
        a_lo = max(0, layer - B + 1)
        a_hi = min(A - 1, layer)
        for a in range(a_lo, a_hi + 1):
            b = layer - a
            yield a, b


def _weighted_shuffle(candidates, grid, r, c):
    """Order candidates without replacement, biased by each candidate's
    effective weight (static Tile.weight, optionally modulated by a
    learned context scorer -- see WFCGrid.effective_weight), so
    backtracking tries higher-weight/more-plausible tiles first more
    often -- consistent with wfc_core.WFCGrid.collapse's weighted choice,
    not just a uniform shuffle."""
    pool = sorted(candidates)
    ordered = []
    while pool:
        weights = [grid.effective_weight(r, c, tid) for tid in pool]
        pick = random.choices(pool, weights=weights, k=1)[0]
        ordered.append(pick)
        pool.remove(pick)
    return ordered


def _backtracking_search(grid, budget, backtrack_events):
    """Recursive depth-first backtracking: pick the entropy cell, try each
    of its candidate tiles (in random order, to preserve aperiodicity),
    propagate, and recurse. On contradiction, undo just that one decision
    and try the next candidate -- this is real backtracking, not a
    whole-grid restart, matching the base paper's description of I-WFC as
    combining backtracking with constraint propagation (Section III-C4).

    `budget` is a single-element list used as a mutable counter so nested
    recursive calls can share and decrement one global attempt limit,
    keeping worst-case runtime bounded on pathological inputs.

    `backtrack_events` is a single-element list counting actual backtrack
    events specifically -- i.e. a candidate being discarded, either because
    it immediately caused a Contradiction or because the recursive search
    beneath it failed. This is distinct from `budget`, which decrements on
    every attempt including ones that succeed on the first try; conflating
    the two would overstate how much backtracking actually happened.
    """
    cell = grid.entropy_cell()
    if cell is None:
        return True  # every cell holds exactly one candidate: accepted result

    r, c = cell
    candidates = _weighted_shuffle(sorted(grid.cells[r][c]), grid, r, c)
    snapshot = grid.snapshot()

    for tid in candidates:
        budget[0] -= 1
        if budget[0] <= 0:
            raise RuntimeError("I-WFC backtracking budget exhausted")

        grid.cells[r][c] = {tid}
        try:
            grid.propagate(r, c)
        except Contradiction:
            grid.restore(snapshot)
            backtrack_events[0] += 1
            continue

        if _backtracking_search(grid, budget, backtrack_events):
            return True

        grid.restore(snapshot)  # this choice didn't lead anywhere; undo and try the next
        backtrack_events[0] += 1

    return False


def solve_i_wfc(tileset, C, top_row_tiles, left_col_tiles, boundary_sides, backtrack_budget=20000, enforce_layer2=False, context_scorer=None, candidate_tile_ids=None):
    """Solve one C x C subgrid (I-WFC), inheriting fixed edges from
    already-generated neighbors, using real backtracking search.

    top_row_tiles: list of C tile ids for row 0, or None if this subgrid
        has no upper neighbor (i.e. it sits on the grid's top edge).
    left_col_tiles: list of C tile ids for column 0, or None if this
        subgrid has no left neighbor.
    boundary_sides: which of {'n','s','w','e'} are this subgrid's *true*
        exterior edges (facing outside the whole N-WFC grid, not another
        subgrid) and should therefore be wall-constrained.

    Returns (tile_id_grid, backtrack_events_count). backtrack_events_count
    is the number of times a candidate had to be discarded and retried --
    zero means the subgrid was solved in one pass with no backtracking at
    all. Raises RuntimeError if no accepted subgrid solution is found
    within the backtracking budget -- the "I-WFC may fail to find a
    suitable tile" case the base paper describes in Section III-C6.
    """
    grid = WFCGrid(rows=C, cols=C, tileset=tileset, boundary_sides=boundary_sides, enforce_layer2=enforce_layer2, context_scorer=context_scorer, candidate_tile_ids=candidate_tile_ids)

    pinned = []
    if top_row_tiles is not None:
        for c, tid in enumerate(top_row_tiles):
            grid.pin(0, c, tid)
            pinned.append((0, c))
    if left_col_tiles is not None:
        for r, tid in enumerate(left_col_tiles):
            grid.pin(r, 0, tid)
            pinned.append((r, 0))

    try:
        for (r, c) in pinned:
            grid.propagate(r, c)
    except Contradiction as exc:
        raise RuntimeError(
            f"I-WFC subgrid's inherited preconstraints are themselves "
            f"contradictory (before any collapse even started): {exc}"
        )

    budget = [backtrack_budget]
    backtrack_events = [0]
    if not _backtracking_search(grid, budget, backtrack_events):
        raise RuntimeError(
            f"I-WFC found no accepted solution for a {C}x{C} subgrid within "
            f"{backtrack_budget} backtracking steps, given its inherited preconstraints"
        )

    return grid.as_tile_ids(), backtrack_events[0]


def _candidate_ids_for_subgrid(tileset, assigned_room_type):
    """Given a subgrid's assignment from a room_plan (a specific room
    type, "CORRIDOR" for connective/unrestricted tissue, or None for no
    restriction), return the set of tile ids that subgrid's cells may
    initially choose from.

    EXT is deliberately excluded from every restricted candidate set:
    EXT tiles are all-wall on every side (see tileset_core.json), so an
    EXT cell appearing inside a room-designated subgrid always produces a
    walled-off, disconnected void -- visible as a jarring rectangular
    notch cut into the middle of a room. An earlier version included EXT
    here as a safety valve against over-constrained corners failing to
    solve; that traded a rare hard failure for a much more common visual
    defect. Removing it instead relies on zoning.py's
    solve_zoned_with_exact_counts retry wrapper to recover from the
    occasional resulting generation failure by trying a fresh subgrid
    assignment -- a better trade given the tileset's ~60-70 variants per
    room type make outright failure genuinely rare.

    "CORRIDOR" assignments allow COR and ENT (so the entrance can still
    appear somewhere) but likewise no longer include EXT.
    """
    if assigned_room_type is None:
        return None  # no restriction -- behaves exactly as before zoning existed

    if assigned_room_type == "CORRIDOR":
        allowed_types = {"COR"}
    elif assigned_room_type == "CORRIDOR_ENTRANCE":
        allowed_types = {"COR", "ENT"}
    else:
        allowed_types = {assigned_room_type}

    return {tid for tid, t in tileset.tiles.items() if t.room_type in allowed_types}


def solve_nwfc(tileset, A, B, C, backtrack_budget_per_subgrid=20000, max_exterior_backtracks=200,
                enforce_layer2=False, context_scorer=None, room_plan=None, max_time_seconds=None):
    """Run the full N-WFC exterior process: A x B subgrids of size C x C,
    solved in diagonal order and stitched into one M x N grid.

    max_time_seconds: an optional wall-clock ceiling checked on every
    iteration of the exterior backtracking loop (not just once per
    solve_nwfc call) -- without this, a single call with a large
    exterior-backtrack budget can run for many seconds internally
    (each backtrack can require re-solving several subgrids, each with
    its own large internal I-WFC budget) with no way for a caller to
    interrupt it, since it's one call from the outside. Raises
    RuntimeError (the same exception type as an ordinary backtrack
    exhaustion) if exceeded, so callers that already retry on
    RuntimeError don't need special-case handling for this.

    Per Section III-C6 of the base paper, I-WFC can occasionally fail to
    satisfy the preconstraints inherited from its neighbors even with a
    subcomplete tileset -- the paper's pairwise subcompleteness proof
    assumes cells are placed one at a time in strict diagonal order, but a
    real solver using full entropy-based selection and constraint
    propagation (as this one does, and as any practical WFC implementation
    does) can create compound constraints the simple pairwise guarantee
    doesn't cover. When that happens, this is *not* an I-WFC-internal
    backtracking case (solve_i_wfc's own budget) -- it requires the
    *exterior* process to redo the specific neighboring subgrid(s) that
    produced the bad preconstraint, exactly as the paper describes.

    Returns an NWFCResult. NWFCResult.exterior_backtracks records how many
    times this had to happen -- in a perfectly subcomplete-for-this-solver
    tileset it would be zero; a nonzero value is itself a real, reportable
    metric (see E2 in the experiment plan).
    """
    import time as _nwfc_time
    _start_time = _nwfc_time.time()

    order = list(_diagonal_order(A, B))
    position = {ab: i for i, ab in enumerate(order)}

    subgrids = {}
    restarts = {}
    exterior_backtracks = 0

    i = 0
    while i < len(order):
        if max_time_seconds is not None and _nwfc_time.time() - _start_time > max_time_seconds:
            raise RuntimeError(
                f"N-WFC exceeded its {max_time_seconds}s time budget "
                f"(after {exterior_backtracks} exterior backtracks)"
            )
        a, b = order[i]
        top_row_tiles = None
        if a > 0:
            above = subgrids[(a - 1, b)]
            top_row_tiles = [above[C - 1][c] for c in range(C)]

        left_col_tiles = None
        if b > 0:
            left = subgrids[(a, b - 1)]
            left_col_tiles = [left[r][C - 1] for r in range(C)]

        if top_row_tiles is not None and left_col_tiles is not None:
            assert top_row_tiles[0] == left_col_tiles[0], (
                f"Corner mismatch at subgrid ({a},{b}): "
                f"{top_row_tiles[0]} != {left_col_tiles[0]}"
            )

        boundary_sides = set()
        if a == 0:
            boundary_sides.add("n")
        if a == A - 1:
            boundary_sides.add("s")
        if b == 0:
            boundary_sides.add("w")
        if b == B - 1:
            boundary_sides.add("e")

        candidate_tile_ids = None
        if room_plan is not None:
            candidate_tile_ids = _candidate_ids_for_subgrid(tileset, room_plan.get((a, b)))

        try:
            tile_grid, used_restarts = solve_i_wfc(
                tileset, C, top_row_tiles, left_col_tiles, boundary_sides, backtrack_budget_per_subgrid,
                enforce_layer2=enforce_layer2, context_scorer=context_scorer,
                candidate_tile_ids=candidate_tile_ids,
            )
            subgrids[(a, b)] = tile_grid
            restarts[(a, b)] = used_restarts
            i += 1
        except RuntimeError:
            # Exterior backtracking: the immediate cause is whichever
            # already-solved neighbor produced this subgrid's bad
            # preconstraint. Redo the most recently solved of (a-1,b) and
            # (a,b-1) -- i.e. the one that appears latest in the diagonal
            # order -- by discarding it and everything after it, so the
            # next attempt explores a different solution for it.
            if exterior_backtracks >= max_exterior_backtracks:
                raise RuntimeError(
                    f"N-WFC exceeded {max_exterior_backtracks} exterior backtracks "
                    f"attempting to resolve a conflict at subgrid ({a},{b})"
                )
            exterior_backtracks += 1

            candidates = [ab for ab in ((a - 1, b), (a, b - 1)) if ab in subgrids]
            redo_target = max(candidates, key=lambda ab: position[ab])
            redo_index = position[redo_target]

            for ab in order[redo_index:i + 1]:
                subgrids.pop(ab, None)
                restarts.pop(ab, None)
            i = redo_index

    M = A * (C - 1) + 1
    N = B * (C - 1) + 1
    global_grid = [[None] * N for _ in range(M)]
    for (a, b), tile_grid in subgrids.items():
        row_off = a * (C - 1)
        col_off = b * (C - 1)
        for r in range(C):
            for c in range(C):
                global_grid[row_off + r][col_off + c] = tile_grid[r][c]

    return NWFCResult(global_grid, subgrids, restarts, A, B, C, exterior_backtracks)


def validate_global_edge_consistency(tileset, result: NWFCResult) -> bool:
    """Same accepted-result check as wfc_core.validate_edge_consistency,
    applied to the *stitched* global grid rather than a single WFCGrid.
    Confirms the N-WFC pasting process didn't introduce any mismatch at
    subgrid boundaries."""
    from wfc_core import DIRS, OPPOSITE  # local import to avoid polluting module namespace

    grid = result.global_grid
    rows, cols = result.rows, result.cols
    for r in range(rows):
        for c in range(cols):
            tile = tileset.tiles[grid[r][c]]
            for direction, (dr, dc) in DIRS.items():
                nr, nc = r + dr, c + dc
                if not (0 <= nr < rows and 0 <= nc < cols):
                    continue
                neighbor = tileset.tiles[grid[nr][nc]]
                if tile.edge(direction) != neighbor.edge(OPPOSITE[direction]):
                    return False
    return True